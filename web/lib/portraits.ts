import type { Sprite } from "./sprites";

/**
 * Hand-drawn 24x24 portraits for the current staff: more pixels than the 16x16
 * part-built faces, so each one gets a silhouette and a prop of their own.
 * One letter per pixel, "." is transparent; `extra` adds single pixels (straps,
 * steam, toothpicks) that would make the rows hard to read.
 */

const INK = { k: "#1a1a1a", w: "#ffffff" };

function art(rows: string[], palette: Record<string, string>, extra: [number, number, string][] = []): Sprite {
  const grid = rows.map((r) => r.padEnd(24, ".").slice(0, 24).split(""));
  for (const [r, c, v] of extra) grid[r][c] = v;
  return { rows: grid.map((r) => r.join("")), palette: { ...INK, ...palette } };
}

